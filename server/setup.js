#!/usr/bin/env node
// Discipline server setup tool
// Run once before first launch: node setup.js

const readline = require('readline');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ENV_PATH = path.join(__dirname, '.env');

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise(resolve => rl.question(q, resolve));

async function main() {
  console.log('\n╔════════════════════════════════╗');
  console.log('║   Discipline — Server Setup    ║');
  console.log('╚════════════════════════════════╝\n');

  if (fs.existsSync(ENV_PATH)) {
    const overwrite = await ask('⚠️  A .env file already exists. Overwrite it? (y/N): ');
    if (overwrite.trim().toLowerCase() !== 'y') {
      console.log('Aborted. Existing .env left unchanged.');
      rl.close(); return;
    }
  }

  // Port
  const portInput = await ask('Port to run on (default: 3000): ');
  const port = parseInt(portInput.trim()) || 3000;
  if (port < 1024 || port > 65535) {
    console.error('❌ Invalid port. Use a number between 1024 and 65535.');
    rl.close(); return;
  }

  // JWT secret — always auto-generated, never typed by hand
  const jwtSecret = crypto.randomBytes(32).toString('hex');

  // Optional overrides
  const dbInput = await ask('Database file path (default: ./discipline.db): ');
  const dbPath = dbInput.trim() || './discipline.db';

  const uploadsInput = await ask('Uploads directory (default: ./uploads): ');
  const uploadsDir = uploadsInput.trim() || './uploads';

  const backupsInput = await ask('Backups directory (default: ./backups): ');
  const backupsDir = backupsInput.trim() || './backups';

  const fileSizeInput = await ask('Max upload size in MB (default: 10): ');
  const maxFileSizeMb = parseInt(fileSizeInput.trim()) || 10;

  rl.close();

  const env = [
    `# Generated by setup.js on ${new Date().toISOString()}`,
    ``,
    `JWT_SECRET=${jwtSecret}`,
    `PORT=${port}`,
    `DB_PATH=${dbPath}`,
    `UPLOADS_DIR=${uploadsDir}`,
    `BACKUPS_DIR=${backupsDir}`,
    `MAX_FILE_SIZE_MB=${maxFileSizeMb}`,
  ].join('\n');

  fs.writeFileSync(ENV_PATH, env + '\n');

  console.log('\n✅ .env file written successfully.\n');
  console.log('Settings:');
  console.log(`   Port           : ${port}`);
  console.log(`   Database       : ${dbPath}`);
  console.log(`   Uploads        : ${uploadsDir}`);
  console.log(`   Backups        : ${backupsDir}`);
  console.log(`   Max upload     : ${maxFileSizeMb}MB`);
  console.log(`   JWT secret     : (auto-generated)\n`);
  console.log('Next steps:');
  console.log('   npm install');
  console.log('   pm2 start index.js --name discipline');
  console.log('   pm2 save');
  console.log('   pm2 startup   (then run the command it prints)\n');
}

main().catch(err => { console.error(err); process.exit(1); });
